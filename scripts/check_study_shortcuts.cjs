      await p.locator('.knowledge-card-details summary').first().click();
      assert.equal(await p.locator('.knowledge-card-details').first().evaluate(e=>e.open),true);
      await p.locator('#knowledge-next-top').click();
      assert.match(await p.locator('#knowledge-position').innerText(), /^2 \/ 6/);
      const toolbar = await p.locator('.quick-toolbar').boundingBox();
      const paging = await p.locator('.knowledge-results-toolbar').boundingBox();
      assert.ok(paging.y>=toolbar.y+toolbar.height-1, 'paging is below fixed navigation');
      await p.locator('#knowledge-prev-top').click();
      assert.equal(await p.locator('.knowledge-card-details').first().evaluate(e=>e.open),true);
      await p.locator('[name="knowledge-view"][value="recall"]').check();
      assert.equal(await p.locator('.knowledge-card').count(),1);
      assert.equal(await p.locator('#knowledge-recall-answer').isHidden(),true);
