      assert.equal(await p.locator('.knowledge-reveal').getAttribute('aria-expanded'),'true');
      await p.locator('#knowledge-next-top').click();
      assert.match(await p.locator('#knowledge-position').innerText(), /^2 \/ 72/);
      assert.equal(await p.locator('#knowledge-recall-answer').isHidden(),true);
      await p.locator('#knowledge-prev-top').click();
